import mongoose from "mongoose";

const feeSchema = new mongoose.Schema(
  {
    /*
    |--------------------------------------------------------------------------
    | Student
    |--------------------------------------------------------------------------
    */

    student: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "Student",
      required: true,
      index: true,
    },

    /*
    |--------------------------------------------------------------------------
    | Class
    |--------------------------------------------------------------------------
    */

    class: {
      type: String,
      required: true,
      trim: true,
      index: true,
    },

    /*
    |--------------------------------------------------------------------------
    | Fee Month
    |--------------------------------------------------------------------------
    */

    month: {
      type: String,
      required: true,
      trim: true,
      index: true,
    },

    /*
    |--------------------------------------------------------------------------
    | Total Fee
    |--------------------------------------------------------------------------
    */

    totalAmount: {
      type: Number,
      required: true,
      min: 0,
    },

    /*
    |--------------------------------------------------------------------------
    | Amount Paid
    |--------------------------------------------------------------------------
    */

    paidAmount: {
      type: Number,
      default: 0,
      min: 0,
    },

    /*
    |--------------------------------------------------------------------------
    | Remaining Amount
    |--------------------------------------------------------------------------
    */

    remainingAmount: {
      type: Number,
      default: 0,
      min: 0,
    },

    /*
    |--------------------------------------------------------------------------
    | Fee Status
    |--------------------------------------------------------------------------
    */

    status: {
      type: String,
      enum: [
        "paid",
        "partial",
        "unpaid",
        "overdue",
      ],
      default: "unpaid",
      index: true,
    },

    /*
    |--------------------------------------------------------------------------
    | Due Date
    |--------------------------------------------------------------------------
    */

    dueDate: {
      type: Date,
      default: null,
    },

    /*
    |--------------------------------------------------------------------------
    | Payment Date
    |--------------------------------------------------------------------------
    */

    paymentDate: {
      type: Date,
      default: null,
    },

    /*
    |--------------------------------------------------------------------------
    | Payment Method
    |--------------------------------------------------------------------------
    */

    paymentMethod: {
      type: String,
      enum: [
        "cash",
        "bank",
        "online",
        "other",
      ],
      default: "cash",
    },

    /*
    |--------------------------------------------------------------------------
    | Receipt Number
    |--------------------------------------------------------------------------
    */

    receiptNumber: {
      type: String,
      trim: true,
      default: "",
      index: true,
    },

    /*
    |--------------------------------------------------------------------------
    | Notes
    |--------------------------------------------------------------------------
    */

    notes: {
      type: String,
      trim: true,
      default: "",
      maxlength: 1000,
    },

    /*
    |--------------------------------------------------------------------------
    | Created By
    |--------------------------------------------------------------------------
    */

    createdBy: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "User",
      default: null,
    },
  },
  {
    timestamps: true,
  }
);

/*
|--------------------------------------------------------------------------
| Prevent Duplicate Monthly Fee
|--------------------------------------------------------------------------
|
| One student should normally have one fee record
| for one month.
|
*/

feeSchema.index(
  {
    student: 1,
    month: 1,
  },
  {
    unique: true,
  }
);

const Fee = mongoose.model("Fee", feeSchema);

export default Fee; 